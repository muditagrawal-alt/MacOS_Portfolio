/* ==========================================================================
   Applies an info bank to the repository (Node, no dependencies)
   --------------------------------------------------------------------------
   Used by the setup server (scripts/dev-server.js) when the questionnaire is
   saved, and on its own:

       node setup/apply.js refresh    regenerate everything derived from
                                      js/data/profile.js (after a hand edit)

   What it writes:
     js/data/profile.js        the info bank itself
     assets/me/*               uploaded photo, résumé, certificates, icons
     index.html, ios.html      <title> and link-preview tags (profile:meta)
     manifest.webmanifest      Home Screen name
     api/_owner.js             who the serverless functions speak for
     js/config/config.js       contact-form key / Iris endpoint, if given
     .portfolio/setup.json     "setup done" marker (git-ignored), and the
                               previous info bank's files nothing uses now —
                               removed only when asked (removeLeftovers)
   ========================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { serializeProfile } = require('./profile-format.js');
const SiteMeta = require('./site-meta.js');

const ROOT = path.resolve(__dirname, '..');
const PROFILE_FILE = 'js/data/profile.js';
const MARKER_FILE = '.portfolio/setup.json';
const ASSET_DIR = 'assets/me';
const ALLOWED_UPLOADS = /^assets\/me\/[a-z0-9][a-z0-9._-]{0,80}\.(jpe?g|png|webp|gif|pdf)$/;
const MAX_UPLOAD_BYTES = 15 * 1024 * 1024;

/** Runs profile.js in a sandbox (so hand edits in plain JS syntax still load). */
function readProfile(root = ROOT) {
    const ctx = { window: {} };
    vm.runInNewContext(fs.readFileSync(path.join(root, PROFILE_FILE), 'utf8'), ctx, { filename: PROFILE_FILE, timeout: 1000 });
    if (!ctx.window.PROFILE_DATA || typeof ctx.window.PROFILE_DATA !== 'object') throw new Error(`${PROFILE_FILE} does not define window.PROFILE_DATA`);
    return JSON.parse(JSON.stringify(ctx.window.PROFILE_DATA));
}

/** The same normalisation the site applies (js/data/profile-schema.js). */
function normalize(raw, root = ROOT) {
    const ctx = { window: { PROFILE_DATA: JSON.parse(JSON.stringify(raw || {})) } };
    vm.runInNewContext(fs.readFileSync(path.join(root, 'js/data/profile-schema.js'), 'utf8'), ctx, { timeout: 1000 });
    return ctx.window.PROFILE_DATA;
}

function write(root, file, contents, written, dryRun = false) {
    const full = path.join(root, file);
    if (fs.existsSync(full) && fs.readFileSync(full, 'utf8') === contents) return;
    written.push(file);
    if (dryRun) return;
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, contents);
}

function ownerModule(p) {
    const origins = new Set();
    try { if (p.site.url) origins.add(new URL(p.site.url).origin); } catch (e) { /* not a URL */ }
    if (p.github.user) origins.add(`https://${p.github.user.toLowerCase()}.github.io`);
    const feeds = [];
    const medium = p.link('medium');
    const substack = p.link('substack');
    const handle = (l) => (l.url.match(/@([\w.-]+)/) || [])[1] || l.handle.replace(/^@/, '');
    if (medium && handle(medium)) feeds.push({ source: 'medium', url: `https://medium.com/feed/@${handle(medium)}` });
    if (substack && handle(substack)) feeds.push({ source: 'substack', url: `https://${handle(substack)}.substack.com/feed` });
    return `/* ==========================================================================
   Who the serverless functions speak for — generated by \`npm run setup\`
   --------------------------------------------------------------------------
   The leading underscore keeps Vercel from serving this file as an endpoint.
   The questionnaire rewrites it from the info bank; edit by hand if needed.
   ========================================================================== */

export const OWNER = ${JSON.stringify({ name: p.name, possessive: p.pron.possessive, origins: [...origins], feeds }, null, 4)};
`;
}

/**
 * Rewrites every file derived from the info bank. Returns the files that
 * changed; with { dryRun: true } nothing is written (the test suite uses this
 * to check the pages still match the info bank).
 */
function writeGenerated(raw, root = ROOT, { dryRun = false } = {}) {
    const p = normalize(raw, root);
    const written = [];
    for (const [file, page] of [['index.html', 'mac'], ['ios.html', 'ios']]) {
        const html = fs.readFileSync(path.join(root, file), 'utf8');
        write(root, file, SiteMeta.applyMetaBlock(html, SiteMeta.renderMetaBlock(p, page)), written, dryRun);
    }
    write(root, 'manifest.webmanifest', SiteMeta.renderManifest(p), written, dryRun);
    write(root, 'api/_owner.js', ownerModule(p), written, dryRun);
    return written;
}

/** Updates the two service settings in js/config/config.js, leaving everything else as it is. */
function writeConfig(config, root, written) {
    if (!config) return;
    const file = 'js/config/config.js';
    let src = fs.readFileSync(path.join(root, file), 'utf8');
    const str = (v) => (v ? `'${String(v).replace(/[\\']/g, '')}'` : 'null');
    if ('irisEndpoint' in config) src = src.replace(/IRIS_ENDPOINT:\s*[^,\n]+,/, `IRIS_ENDPOINT: ${str(config.irisEndpoint)},`);
    if ('web3formsKey' in config) src = src.replace(/WEB3FORMS_ACCESS_KEY:\s*[^,\n]+/, `WEB3FORMS_ACCESS_KEY: ${str(config.web3formsKey)}`);
    write(root, file, src, written);
}

function readConfig(root = ROOT) {
    const src = fs.readFileSync(path.join(root, 'js/config/config.js'), 'utf8');
    const pick = (key) => { const m = src.match(new RegExp(`${key}:\\s*'([^']*)'`)); return m ? m[1] : ''; };
    return { irisEndpoint: pick('IRIS_ENDPOINT'), web3formsKey: pick('WEB3FORMS_ACCESS_KEY') };
}

/* ── Leftovers: files the previous info bank used that nothing uses now ── */
const KINDS = { photo: 'photo', resume: 'résumé', certificates: 'certificates', projects: 'project icons', site: 'link preview' };

/** Local files an info bank points at → what they are ("photo", "certificates"…). */
function referencedFiles(raw) {
    const refs = new Map();
    const walk = (v, top) => {
        if (typeof v === 'string') { if (/^assets\/[^\s"]+\.[a-z0-9]{2,5}$/i.test(v)) refs.set(v, KINDS[top] || 'files'); }
        else if (v && typeof v === 'object') Object.entries(v).forEach(([k, x]) => walk(x, top || k));
    };
    walk(raw, '');
    return refs;
}

/** Everything the code, markup and docs could load a file by (its name is enough to keep it). */
function codeText(root) {
    const list = (dir) => {
        const full = path.join(root, dir);
        if (!fs.existsSync(full)) return [];
        return fs.readdirSync(full, { withFileTypes: true }).flatMap(d => (d.isDirectory() ? list(path.join(dir, d.name)) : /\.(js|css|html|json|webmanifest)$/.test(d.name) ? [path.join(dir, d.name)] : []));
    };
    const docs = fs.readdirSync(root).filter(f => f.endsWith('.md'));   // the README's screenshot
    return ['index.html', 'ios.html', 'manifest.webmanifest', ...docs, ...['js', 'css', 'api', 'setup', 'scripts'].flatMap(list)]
        .filter(f => f.split(path.sep).join('/') !== PROFILE_FILE && fs.existsSync(path.join(root, f)))
        .map(f => fs.readFileSync(path.join(root, f), 'utf8')).join('\n');
}

function isLeftover(file, profile, root, code = codeText(root)) {
    const full = path.normalize(path.join(root, file));
    return /^assets\/[\w./-]+$/.test(file) && full.startsWith(path.join(root, 'assets') + path.sep)
        && fs.existsSync(full) && !referencedFiles(profile).has(file) && !code.includes(path.basename(file));
}

/** Deletes the leftovers recorded at the last save, re-checking that each is still unused. */
function removeLeftovers(root = ROOT) {
    const marker = readMarker(root);
    const profile = readProfile(root);
    const code = codeText(root);
    const removed = [];
    for (const { path: file } of marker.leftovers || []) {
        if (!isLeftover(file, profile, root, code)) continue;
        fs.unlinkSync(path.join(root, file));
        removed.push(file);
        // Folders that held only these files go too (assets/photos/thumbs…), never assets/ itself.
        for (let dir = path.dirname(path.join(root, file)); dir.startsWith(path.join(root, 'assets') + path.sep) && fs.readdirSync(dir).length === 0; dir = path.dirname(dir)) fs.rmdirSync(dir);
    }
    writeMarker(root, { ...marker, leftovers: [] });
    return removed;
}

/**
 * Saves a questionnaire submission.
 * @param {object} profile  the info bank (as the questionnaire built it)
 * @param {{ files?: {path:string, data:string}[], config?: {web3formsKey?:string, irisEndpoint?:string} }} extras
 *        files: data: URLs to store at assets/me/…, already referenced from `profile`
 * @returns {{ written: string[], leftovers: {path:string, kind:string}[] }}
 */
function saveSubmission(profile, { files = [], config } = {}, root = ROOT) {
    if (!profile || typeof profile !== 'object' || !String(profile.name || '').trim()) throw new Error('A name is required.');
    const before = fs.existsSync(path.join(root, PROFILE_FILE)) ? referencedFiles(readProfile(root)) : new Map();
    const written = [];
    for (const f of files) {
        if (!ALLOWED_UPLOADS.test(f.path)) throw new Error(`Refusing to write ${f.path}`);
        const m = String(f.data).match(/^data:[\w/+.-]+;base64,([A-Za-z0-9+/=]+)$/);
        if (!m) throw new Error(`${f.path}: not a base64 data URL`);
        const buf = Buffer.from(m[1], 'base64');
        if (buf.length > MAX_UPLOAD_BYTES) throw new Error(`${f.path} is larger than 15 MB`);
        fs.mkdirSync(path.join(root, ASSET_DIR), { recursive: true });
        fs.writeFileSync(path.join(root, f.path), buf);
        written.push(f.path);
    }
    write(root, PROFILE_FILE, serializeProfile(profile), written);
    writeConfig(config, root, written);
    written.push(...writeGenerated(profile, root));
    // Still-pending leftovers from an earlier save, plus what this one made unused.
    const code = codeText(root);
    const candidates = new Map([...(readMarker(root).leftovers || []).map(l => [l.path, l.kind]), ...before]);
    const leftovers = [...candidates].filter(([file]) => isLeftover(file, profile, root, code)).map(([file, kind]) => ({ path: file, kind }));
    markDone(profile.name, root, leftovers);
    return { written, leftovers };
}

function readMarker(root = ROOT) {
    try { return JSON.parse(fs.readFileSync(path.join(root, MARKER_FILE), 'utf8')); } catch (e) { return {}; }
}

function writeMarker(root, data) {
    const full = path.join(root, MARKER_FILE);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, JSON.stringify(data, null, 2) + '\n');
}

function markDone(name, root = ROOT, leftovers = []) {
    writeMarker(root, { completedAt: new Date().toISOString(), name: name || null, leftovers });
}

function isSetupDone(root = ROOT) {
    return fs.existsSync(path.join(root, MARKER_FILE));
}

module.exports = { readProfile, normalize, writeGenerated, saveSubmission, removeLeftovers, readConfig, markDone, isSetupDone, ALLOWED_UPLOADS };

if (require.main === module) {
    const cmd = process.argv[2];
    if (cmd === 'refresh') {
        const changed = writeGenerated(readProfile());
        console.log(changed.length ? `Updated: ${changed.join(', ')}` : 'Everything already matches the info bank.');
    } else {
        console.log('Usage: node setup/apply.js refresh   (regenerate files derived from js/data/profile.js)');
        process.exit(1);
    }
}
